/**
 * Create a translator function bound to the active language ('ar' or 'en').
 * Supports optional interpolation params `{ key: value }` or fallback string.
 */
export function createTranslator(lang = 'ar') {
  const activeDict = translations[lang] || translations.ar;
  const fallbackDict = translations.en;

  return function t(key, paramsOrFallback) {
    let text = activeDict[key];
    if (text === undefined) {
      text = fallbackDict[key];
    }
    if (text === undefined) {
      text = typeof paramsOrFallback === 'string' ? paramsOrFallback : key;
    }
    if (paramsOrFallback && typeof paramsOrFallback === 'object') {
      return String(text).replace(/\{\{?(\w+)\}?\}/g, (_, k) =>
        paramsOrFallback[k] !== undefined && paramsOrFallback[k] !== null
          ? String(paramsOrFallback[k])
          : `{${k}}`
      );
    }
    return text;
  };
}

export default translations;
